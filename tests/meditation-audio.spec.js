import {test,expect} from '@playwright/test';
for(const width of [1440,390])test('guided meditation audio '+width,async({page})=>{
 test.setTimeout(90000);
 await page.setViewportSize({width,height:1000});
 // Isolate the player from unrelated signed-in header/admin content.
 await page.route(url=>url.pathname==='/',route=>route.fulfill({contentType:'text/html',body:'<!doctype html><body></body>'}));
 await page.addInitScript(()=>{const NativeAudio=window.Audio;window.reviewAudios=[];window.Audio=function(...args){const a=new NativeAudio(...args);window.reviewAudios.push(a);return a;};});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/standalone/member-design-test.html?feature=meditation');
 const shell=page.frameLocator('#ci-review-frame'),session=shell.frameLocator('#experienceFrame');
 await expect(shell.locator('#meditationDesignPlay')).toBeEnabled();
 await shell.getByRole('button',{name:'MEDITATION MODES',exact:true}).click();
 await shell.locator('[data-med-mode="guided"]').click();
 await shell.locator('[data-med-time="10"]').click();
 await expect(shell.locator('#experienceFrame')).toHaveAttribute('src',/t=10&mode=guided/);
 await shell.locator('#meditationDesignPlay').click();
 const audio=()=>session.locator('body').evaluate(()=>{const a=window.reviewAudios.find(a=>a.src.includes('coming-back'));if(!a)return {paused:true,time:0};return {paused:a.paused,time:a.currentTime,duration:a.duration,error:a.error?.code};});
 await expect.poll(async()=>(await audio()).paused).toBe(false);
 await expect.poll(async()=>(await audio()).time).toBeGreaterThan(.5);
 await page.screenshot({path:'test-results/meditation-audio-'+width+'.png',fullPage:true});
 await shell.locator('#meditationDesignPlay').click();
 await expect.poll(async()=>(await audio()).paused).toBe(true);
 await shell.locator('#meditationDesignPlay').click();
 await expect.poll(async()=>(await audio()).paused).toBe(false);
 await session.locator('body').evaluate(()=>window.postMessage({type:'ci-meditation-command',command:'seek',ratio:.5},location.origin));
 await expect.poll(async()=>(await audio()).time).toBeGreaterThan(299);
 await session.locator('body').evaluate(()=>window.postMessage({type:'ci-meditation-command',command:'seek',ratio:1},location.origin));
 await expect(session.locator('#player')).toHaveAttribute('data-state','complete');
 await expect.poll(async()=>(await audio()).paused).toBe(true);
 await shell.locator('#meditationDesignPlay').click();
 await expect.poll(async()=>(await audio()).time).toBeLessThan(5);
 await expect.poll(async()=>(await audio()).paused).toBe(false);
 await shell.locator('[data-med-command="menu"]').click();
 await shell.locator('[data-med-mode="unguided"]').click();
 await expect(session.locator('#player')).toHaveAttribute('data-state','ready');
 expect(errors).toEqual([]);
});
