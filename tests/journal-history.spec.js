import {test,expect} from '@playwright/test';
for(const width of [1040,390]) test(`Journal dates and saved revisions ${width}`,async({page},testInfo)=>{
 await page.setViewportSize({width,height:1000});
 await page.route('**/*.supabase.co/**',r=>r.fulfill({contentType:'application/json',body:'[]'}));
 await page.addInitScript(()=>{if(!localStorage.getItem('journal-test-seeded')){localStorage.setItem('journal-test-seeded','1');localStorage.setItem('ci_notes',JSON.stringify([{id:'history-test',cat:'note',text:'Original journal entry',ts:1700000000000}]));}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/standalone/member-design-test.html?feature=journal');
 const f=page.frameLocator('#ci-review-frame').frameLocator('#experienceFrame');
 const entry=f.locator('#page-mynotes textarea[data-id="history-test"]');
 await expect(entry).toBeVisible();
 const meta=f.locator('#page-mynotes [data-journal-history="history-test"]');
 await expect(meta).toContainText('Last modified: Not recorded');
 await expect(meta).not.toContainText('Created: Not recorded');
 await entry.fill('First saved change <script>safe text</script>');await entry.blur();
 await expect(meta).toContainText('1 changes');
 await entry.fill('Second saved change');await entry.blur();
 const select=entry.locator('..').locator('select');
 await select.selectOption({index:1});
 await expect(meta).toContainText('3 changes');
 await meta.locator('summary').click();
 await expect(meta).toContainText('Original journal entry');
 await expect(meta).toContainText('First saved change <script>safe text</script>');
 await expect(meta.locator('script')).toHaveCount(0);
 await entry.dispatchEvent('change');await expect(meta).toContainText('3 changes');
 await page.reload();await expect(meta).toContainText('3 changes');await expect(entry).toHaveValue('Second saved change');
 await meta.locator('summary').click();
 await meta.screenshot({path:testInfo.outputPath('journal-history.png')});
 await f.locator('#page-mynotes [onclick*=notesShowAdd]').click();
 const add=f.locator('#page-mynotes textarea[data-add="note"]');await add.fill('New journal entry');await add.blur();
 const fresh=f.locator('#page-mynotes [data-journal-history]:not([data-journal-history="history-test"])');
 await expect(fresh).toContainText('0 changes');await expect(fresh).not.toContainText('Not recorded');
 expect(errors).toEqual([]);
});
