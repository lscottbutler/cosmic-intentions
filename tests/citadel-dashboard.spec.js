import { test, expect } from '@playwright/test';
for (const width of [1440, 390]) {
 test(`Citadel one-click list, actions and linked entries ${width}`, async ({page}) => {
  test.setTimeout(120000);
  await page.setViewportSize({width,height:1000});
  const errors=[];page.on('pageerror',error=>errors.push(error.message));
  await page.route('**/*',async route=>{
   const u=new URL(route.request().url());
   if(/supabase\.co$|sentry\.io$/.test(u.hostname)||route.request().method()!=='GET')return route.fulfill({status:200,contentType:'application/json',body:'[]'});
   if(u.pathname.startsWith('/.netlify/'))return route.fulfill({status:200,contentType:'application/json',body:'{}'});
   if(u.origin==='http://localhost:8090'&&/^\/assets\/.*\.js$/.test(u.pathname)){
    const response=await route.fetch();let body=await response.text();
    for(const [a,b] of Object.entries({'I AM LAUNCHING COSMIC INTENTIONS GLOBALLY THIS SEPTEMBER':'I AM FINISHING MY FIRST SHORT STORY','I AM PERFECT EYE HEALTH':'I AM BUILDING A CONSISTENT READING HABIT','I AM THE PROUD OWNER OF A XIAOMI SU7':'I AM EXPLORING A NEW WALKING ROUTE','Draft the launch announcement':'Draft the opening scene'}))body=body.split(a).join(b);
    return route.fulfill({response,body});
   }return route.continue();
  });
  await page.addInitScript(()=>{if(localStorage.getItem('ci_dashboard_fixture_seeded'))return;localStorage.setItem('ci_dashboard_fixture_seeded','1');localStorage.setItem('ci_notes','[]');localStorage.setItem('ci_wrapup_actions',JSON.stringify([{id:77,text:'Organize the desk',done:false},{id:78,text:'Read yesterday’s draft',done:true}]));});
  await page.goto('/standalone/member-design-test.html');
  await expect(page.locator('#review-status')).toContainText('Test improvements on',{timeout:25000});
  await page.screenshot({path:`test-results/citadel-dashboard-${width}-home.png`,fullPage:true});
  await page.locator('#to-do').click();
  await expect(page.getByRole('heading',{name:'Your to-do list',exact:true})).toBeVisible();
  const list=page.locator('#dashboard-task-list');
  await expect(list.getByText('Draft the opening scene',{exact:true})).toBeVisible({timeout:25000});
  await expect(list.getByText('Organize the desk',{exact:true})).toBeVisible();
  await expect(list.getByText('Read yesterday’s draft',{exact:true})).toBeHidden();
  await expect(list.getByText('I AM FINISHING MY FIRST SHORT STORY',{exact:true}).first()).toBeVisible();
  const goalGroup=list.locator('.dashboard-task-group[data-goal-id="pv1"]');
  await expect(goalGroup.locator('summary')).toContainText('I AM FINISHING MY FIRST SHORT STORY');
  await expect(list.getByText('I AM FINISHING MY FIRST SHORT STORY',{exact:true})).toHaveCount(1);
  await expect(list.locator('.dashboard-task .dashboard-goal')).toHaveCount(0);
  await goalGroup.locator('summary').click();
  await expect(list.getByText('Draft the opening scene',{exact:true})).toBeHidden();
  await expect(list.getByText('Organize the desk',{exact:true})).toBeVisible();
  await page.getByLabel('Show completed').check();
  await expect(goalGroup).not.toHaveAttribute('open','');
  await goalGroup.locator('summary').click();
  await page.getByLabel('Show completed').check();
  await expect(list.getByText('Read yesterday’s draft',{exact:true})).toBeVisible();
  await page.screenshot({path:`test-results/citadel-dashboard-${width}-todos.png`,fullPage:true});
  const task=list.locator('.dashboard-task').filter({has:page.getByText('Draft the opening scene',{exact:true})});
  await task.getByRole('button',{name:'Add note',exact:true}).click();
  await expect(page.locator('#dashboard-entry-goal')).toHaveValue('pv1');
  await expect(page.locator('#dashboard-entry-task')).not.toHaveValue('');
  await page.getByLabel('Entry',{exact:true}).fill('Keep the opening scene simple.');
  await page.getByRole('button',{name:'Save note',exact:true}).click();
  await expect(page.locator('#dashboard-entry-list')).toContainText('Keep the opening scene simple.');
  await page.locator('[data-dashboard-view="tasks"]').click();
  await expect(task).toContainText('Note · Keep the opening scene simple.');
  await task.getByRole('button',{name:'Journal',exact:true}).click();
  await page.getByLabel('Entry',{exact:true}).fill('I worked on the scene and found a clearer beginning.');
  await page.getByRole('button',{name:'Save journal entry',exact:true}).click();
  await page.locator('[data-dashboard-view="tasks"]').click();
  await expect(task).toContainText('Journal · I worked on the scene');
  await task.getByRole('checkbox').check();
  await expect(task).toHaveClass(/is-complete/);
  await task.getByRole('checkbox').uncheck();
  await page.locator('#dashboard-task-text').fill('Review the second scene');
  await page.locator('#dashboard-task-goal').selectOption('pv1');
  await page.getByRole('button',{name:'Add to-do',exact:true}).click();
  await expect(list.getByText('Review the second scene',{exact:true})).toBeVisible();
  await expect(goalGroup.getByText('Review the second scene',{exact:true})).toBeVisible();
  await expect(goalGroup.locator('summary')).toHaveCount(1);
  await expect(list.getByText('I AM FINISHING MY FIRST SHORT STORY',{exact:true})).toHaveCount(1);
  await page.screenshot({path:`test-results/citadel-goal-groups-${width}.png`,fullPage:true});
  await page.locator('#dashboard-task-text').fill('Take a walk');
  await page.locator('#dashboard-task-goal').selectOption('');
  await page.getByRole('button',{name:'Add to-do',exact:true}).click();
  await expect(list.getByText('Take a walk',{exact:true})).toBeVisible();
  await page.locator('[data-dashboard-view="notes"]').click();
  await page.locator('#dashboard-entry-goal').selectOption('');
  await page.getByLabel('Entry',{exact:true}).fill('<img src=x onerror="alert(1)"> A general idea.');
  await page.getByRole('button',{name:'Save note',exact:true}).click();
  await expect(page.locator('#dashboard-entry-list')).toContainText('<img src=x');
  await expect(page.locator('#dashboard-entry-list img')).toHaveCount(0);
  await page.screenshot({path:`test-results/citadel-dashboard-${width}-notes.png`,fullPage:true});
  await page.getByRole('button',{name:'Close dashboard',exact:true}).click();
  await expect(page.locator('#to-do')).toBeFocused();
  await page.locator('#add-note').click();await page.locator('[data-dashboard-view="journal"]').click();
  await expect(page.locator('#dashboard-entry-list')).toContainText('I worked on the scene');
  await page.screenshot({path:`test-results/citadel-dashboard-${width}-journal.png`,fullPage:true});
  await page.getByRole('button',{name:'Close dashboard',exact:true}).click();
  const app=page.frameLocator('#ci-review-frame').frameLocator('#experienceFrame');
  const saved=await app.locator('body').evaluate(()=>JSON.parse(localStorage.getItem('ci_notes')));
  expect(saved.some(note=>note.cat==='goal-note'&&note.goal==='pv1'&&note.taskKey&&note.text==='Keep the opening scene simple.')).toBe(true);
  expect(saved.some(note=>note.cat==='note'&&note.goal==='pv1'&&note.taskKey)).toBe(true);
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  // A blocked local write must keep the draft and must never say Saved.
  await page.locator('#add-note').click();
  await expect(page.locator('#dashboard-entry-text')).toBeVisible({timeout:20000});
  await app.locator('body').evaluate(()=>{const original=Storage.prototype.setItem;window.restoreDashboardStorage=()=>{Storage.prototype.setItem=original;};Storage.prototype.setItem=function(key,value){if(key==='ci_notes')throw new Error('Review simulated local storage failure');return original.call(this,key,value);};});
  await page.locator('#dashboard-entry-text').fill('Keep this draft when storage is unavailable.');
  await page.getByRole('button',{name:'Save note',exact:true}).click();
  await expect(page.locator('#dashboard-state')).toContainText('Could not save');
  await expect(page.locator('#dashboard-entry-text')).toHaveValue('Keep this draft when storage is unavailable.');
  await page.locator('[data-dashboard-view="journal"]').click();
  await expect(page.locator('#dashboard-entry-text')).toHaveValue('');
  await page.locator('[data-dashboard-view="notes"]').click();
  await expect(page.locator('#dashboard-entry-text')).toHaveValue('Keep this draft when storage is unavailable.');
  await app.locator('body').evaluate(()=>window.restoreDashboardStorage());
  await page.getByRole('button',{name:'Save note',exact:true}).click();
  await expect(page.locator('#dashboard-state')).toContainText('Entry saved on this device');
  expect(errors).toEqual([]);
 });
}
